import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'prom-precheck-'));
process.env.PROMETHEUS_DATA_DIR = root;
process.env.PROMETHEUS_WORKSPACE_DIR = path.join(root, 'workspace');
fs.mkdirSync(process.env.PROMETHEUS_WORKSPACE_DIR, { recursive: true });
async function main() {
  const { CronScheduler } = await import('./cron-scheduler');
  const { loadRunLog } = await import('./schedule-memory');
  const { getConfig } = require('../../config/config');
  (getConfig().getConfig() as any).tools = { permissions: { shell: { approval_mode: 'lite' } } };
  let calls = 0;
  let context = '';
  const scheduler = new CronScheduler({ storePath: path.join(root, 'jobs.json'), broadcast: () => {}, handleChat: async (...args: any[]) => { calls++; context = JSON.stringify(args); return { text: 'OK' } as any; } });
  const create = (precheck?: any) => scheduler.createJob({ name: 'gate regression', prompt: 'Say OK', type: 'recurring', schedule: '* * * * *', precheck } as any);
  const gate = { command: 'node -e "console.log(\'NOOP\')"', skipWhen: 'stdout_match', pattern: '^NOOP$', timeoutMs: 15000 };
  const skip = create(gate);
  await scheduler.runJobNow(skip.id);
  assert.equal(calls, 0, 'noop must not start model');
  assert.equal(loadRunLog(skip.id).runs.at(-1)?.status, 'skipped');
  const go = create({ ...gate, command: 'node -e "console.log(\'WORK_AVAILABLE\')"' });
  await scheduler.runJobNow(go.id);
  assert.equal(calls, 1);
  assert.match(context, /WORK_AVAILABLE/);
  const failed = create({ ...gate, command: 'node -e "process.exit(7)"' });
  await scheduler.runJobNow(failed.id);
  assert.equal(calls, 1);
  assert.equal(loadRunLog(failed.id).runs.at(-1)?.status, 'failed');
  const timeout = create({ ...gate, command: 'node -e "setTimeout(()=>{},10000)"', timeoutMs: 500 });
  await scheduler.runJobNow(timeout.id);
  assert.equal(loadRunLog(timeout.id).runs.at(-1)?.status, 'failed');
  assert.equal(calls, 1);
  // Regression: run_command clamps yield to >= 1s, so a precheck slower than that
  // used to come back [still running] with exitCode null and be recorded as failed.
  const slowNoop = create({ ...gate, command: 'node -e "setTimeout(()=>console.log(\'NOOP\'),2500)"' });
  await scheduler.runJobNow(slowNoop.id);
  assert.equal(loadRunLog(slowNoop.id).runs.at(-1)?.status, 'skipped', 'slow noop precheck must skip, not fail');
  assert.equal(calls, 1, 'slow noop must not start model');
  const slowGo = create({ ...gate, command: 'node -e "setTimeout(()=>console.log(\'WORK_AVAILABLE\'),2500)"' });
  await scheduler.runJobNow(slowGo.id);
  assert.equal(calls, 2, 'slow work precheck must start model');
  assert.match(context, /WORK_AVAILABLE/);
  const plain = create(); await scheduler.runJobNow(plain.id); assert.equal(calls, 3);
  scheduler.updateJob(skip.id, { precheck: null } as any);
  assert.equal(skip.precheck, undefined);
  await scheduler.runJobNow(skip.id); assert.equal(calls, 4);
  assert.throws(() => create({ ...gate, pattern: '[' }));
  assert.throws(() => create({ ...gate, timeoutMs: -1 }));
  const { evaluateSchedulePrecheck } = await import('./schedule-precheck');
  const result = (stdout: string, exitCode = 0, reason = 'exit') => async () => ({ stdout, exitCode, reason });
  assert.equal((await evaluateSchedulePrecheck(gate as any, result('WORK'))).status, 'go');
  assert.equal((await evaluateSchedulePrecheck({ ...gate, skipWhen: 'exit_nonzero' } as any, result('', 2))).status, 'skipped');
  assert.equal((await evaluateSchedulePrecheck({ ...gate, skipWhen: 'exit_nonzero' } as any, result('', 1, 'spawn_error'))).status, 'failed');
}
main().then(() => process.exit(0), error => { console.error(error); process.exit(1); });
