import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { normalizeContentReview, reviewMediaPath } from './content-review.js';
import { createFinalActionApprovalScope, grantFinalActionApproval, consumeFinalActionApproval } from './final-action-approvals.js';

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'content-review-'));
process.env.PROMETHEUS_DATA_DIR = path.join(root, 'data');
process.env.PROMETHEUS_WORKSPACE_DIR = path.join(root, 'workspace');
async function main() {
  const original = { kind:'post', text:'A'.repeat(16000), account:'@example', media:[{kind:'image',path:'images/test.png'}] };
  const review = normalizeContentReview(original)!;
  assert.equal(review.text.length, 16000);
  original.media[0].path = 'changed.png';
  assert.equal(review.media[0].path, 'images/test.png');
  for (const bad of ['../a.png','https://example.com/a.png','C:/a.png','/a.png','a/%2e%2e/b.png','a.svg','a.png?x=1','a//b.png']) assert.throws(()=>reviewMediaPath(bad));
  assert.throws(()=>normalizeContentReview({kind:'post',text:'x'.repeat(32001)}));
  assert.throws(()=>normalizeContentReview({kind:'post',media:[{kind:'image',path:'x.mp4'}]}));
  const { getApprovalQueue, serializeApprovalForClient } = await import('./verification-flow.js');
  const queue = getApprovalQueue();
  const scope = createFinalActionApprovalScope({actionKind:'post', contentReview:review,nextToolName:'browser_click',nextToolArgs:{ref:'post'}});
  const approval = queue.create({sessionId:'fixture',toolName:'request_final_action_approval',toolArgs:{},approvalKind:'final_action',action:'Post fixture',policyTier:'commit',riskScore:7,affectedSystems:[],finalAction:scope});
  assert.equal(serializeApprovalForClient(approval).finalAction.contentReview.text.length,16000);
  let granted = false; queue.onResolve(approval.id, ok => { granted=ok; });
  queue.update(approval.id,{contentReviewFeedback:'Use revised caption'});
  queue.resolve(approval.id,false,'content_changes');
  assert.equal(granted,false);
  assert.equal(queue.resolve(approval.id,true),null);
  assert.equal(queue.get(approval.id)?.contentReviewFeedback,'Use revised caption');
  grantFinalActionApproval('fixture','grant',scope);
  assert.equal(consumeFinalActionApproval({sessionId:'other',approvalId:'grant',toolName:'browser_click',toolArgs:{ref:'post'}}).ok,false);
  assert.equal(consumeFinalActionApproval({sessionId:'fixture',approvalId:'grant',toolName:'browser_click',toolArgs:{ref:'wrong'}}).ok,false);
  assert.equal(consumeFinalActionApproval({sessionId:'fixture',approvalId:'grant',toolName:'browser_click',toolArgs:{ref:'post'}}).ok,true);
  assert.equal(consumeFinalActionApproval({sessionId:'fixture',approvalId:'grant',toolName:'browser_click',toolArgs:{ref:'post'}}).ok,false);
  const store = await import('./proposals/proposal-store.js');
  const proposal = store.createProposal({type:'general',priority:'medium',title:'Content preview fixture',summary:'Fixture',details:'Fixture',sourceAgentId:'fixture',affectedFiles:[],requiresBuild:false,contentReview:{...review,kind:'proposal'}});
  const changed = store.updatePendingProposal(proposal.id,{contentReview:{...review,kind:'proposal',text:'Changed'}});
  assert.equal(changed.ok,true);
  const loaded = store.loadProposal(proposal.id)!;
  assert.equal(loaded.version,2);
  assert.equal(loaded.contentReview?.text,'Changed');
  assert.equal(loaded.revisionHistory[0].snapshot.contentReview?.text.length,16000);
  const generation = queue.create({sessionId:'fixture',toolName:'generate_image',toolArgs:{prompt:'First prompt',reference_images:['images/ref.png']},action:'Generate',policyTier:'commit',riskScore:5,affectedSystems:[]});
  assert.ok(generation.contentReview?.text.startsWith('First prompt'));
  queue.update(generation.id,{toolArgs:{prompt:'Second prompt'}});
  assert.ok(generation.contentReview?.text.startsWith('Second prompt'));
  assert.equal(generation.contentReview?.media[0].path,'images/ref.png');
  const projectApi = await import('../media-engine/project.js');
  const p = await projectApi.createProject(process.env.PROMETHEUS_WORKSPACE_DIR!, {title:'Review regression'} as any);
  await projectApi.applyOps(process.env.PROMETHEUS_WORKSPACE_DIR!,p.id,[{op:'shot.add',title:'Opening',prompt:'Original video prompt',durationSec:5}] as any);
  const {videoContentReview} = await import('./video-content-review.js');
  const video = videoContentReview(process.env.PROMETHEUS_WORKSPACE_DIR!,p.id,{},1)!;
  assert.ok(video.text.includes('Original video prompt'));
  assert.equal(video.cost,'Quoted: $1.00');
  const shotId = projectApi.loadProject(process.env.PROMETHEUS_WORKSPACE_DIR!,p.id).shots[0].id;
  await projectApi.applyOps(process.env.PROMETHEUS_WORKSPACE_DIR!,p.id,[{op:'shot.update',id:shotId,prompt:'Changed video prompt'}]);
  assert.notEqual(JSON.stringify(video),JSON.stringify(videoContentReview(process.env.PROMETHEUS_WORKSPACE_DIR!,p.id,{},1)));
  console.log('PASS content-review validation, serialization, rejection, grants, proposal revisions, generation updates and video previews');
}
main().then(()=>{fs.rmSync(root,{recursive:true,force:true});process.exit(0)}).catch(e=>{console.error(e);process.exit(1)});
