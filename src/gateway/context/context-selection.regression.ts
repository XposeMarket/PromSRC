import assert from 'node:assert/strict';
import { resolveModelContextProfile, buildContextBudget, rememberProviderContextMetadata } from './model-context';
import { validateContextSelection } from './context-selection';
const cfg = (selection?: any, account='default') => ({ llm: { provider: 'openai_codex', accountId: account, providers: {} }, session: { contextSelections: selection ? { [`openai_codex/gpt-6.1-sol/${account}`]: selection } : {} } });
const profile = (c: any = cfg()) => resolveModelContextProfile('openai_codex','gpt-6.1-sol',undefined,c);
const standard = profile();
assert.equal(standard.contextWindowTokens,272000);
assert.equal(standard.maxContextWindowTokens,872000);
assert.throws(() => validateContextSelection({mode:'maximum'},standard), /Acknowledge/);
assert.throws(() => validateContextSelection({mode:'custom',tokens:900000,extendedAcknowledged:true},standard), /between/);
assert.throws(() => validateContextSelection({mode:'custom',tokens:NaN},standard), /between/);
assert.throws(() => validateContextSelection({mode:'custom',tokens:64000.5},standard), /between/);
assert.equal(profile(cfg({mode:'maximum'})).contextWindowTokens,272000);
assert.equal(profile(cfg({mode:'maximum',extendedAcknowledged:true})).contextWindowTokens,872000);
assert.equal(profile(cfg({mode:'custom',tokens:64000})).contextWindowTokens,64000);
assert.equal(profile(cfg({mode:'custom',tokens:NaN})).contextWindowTokens,272000);
const c:any=cfg({mode:'maximum',extendedAcknowledged:true},'account-a'); c.llm.accountId='account-b';
assert.equal(profile(c).contextWindowTokens,272000,'another account must re-acknowledge');
const routed:any=cfg({mode:'maximum',extendedAcknowledged:true},'account-a');
routed.llm.providers.openai_codex={defaultAccountId:'account-a',baseUrl:'https://endpoint-a.example'};
const accountB=resolveModelContextProfile('openai_codex','gpt-6.1-sol',undefined,routed,'account-b');
assert.equal(accountB.contextAccountId,'account-b');
assert.equal(accountB.contextWindowTokens,272000,'explicit execution account must not inherit default-account consent');
rememberProviderContextMetadata('openai_codex',{name:'gpt-6.1-sol',contextWindowTokens:272000,maxContextWindowTokens:600000},routed,'account-a');
assert.equal(resolveModelContextProfile('openai_codex','gpt-6.1-sol',undefined,routed,'account-a').maxContextWindowTokens,600000);
assert.equal(resolveModelContextProfile('openai_codex','gpt-6.1-sol',undefined,routed,'account-b').maxContextWindowTokens,872000,'metadata must not leak between accounts');
const endpointB={...routed,llm:{...routed.llm,providers:{openai_codex:{...routed.llm.providers.openai_codex,baseUrl:'https://endpoint-b.example'}}}};
assert.equal(resolveModelContextProfile('openai_codex','gpt-6.1-sol',undefined,endpointB,'account-a').maxContextWindowTokens,872000,'metadata must not leak between endpoints');

const haiku=resolveModelContextProfile('anthropic','claude-haiku-5-5',undefined,{llm:{providers:{}}});
assert.equal(haiku.contextWindowTokens,100000); assert.equal(haiku.maxContextWindowTokens,1000000);
assert.match(haiku.contextUsageWarning!, /5x/);
const opus=resolveModelContextProfile('anthropic','claude-opus-5-5',undefined,{llm:{providers:{}}});
assert.equal(opus.contextWindowTokens,1000000); assert.match(opus.contextUsageWarning!, /standard API/);
const customProvider=resolveModelContextProfile('third_party','special',{contextWindowTokens:80000,maxContextWindowTokens:160000},{llm:{providers:{}}});
assert.equal(customProvider.contextWindowTokens,80000);assert.equal(customProvider.maxContextWindowTokens,160000);
assert.equal(buildContextBudget(profile(cfg({mode:'maximum',extendedAcknowledged:true}))).inputBudgetTokens,825136);
assert.deepEqual(validateContextSelection({mode:'standard'},standard),{mode:'standard',tokens:undefined,extendedAcknowledged:false});
console.log('PASS context selection: standard/max/custom, acknowledgement, bounds, account isolation, provider tariffs');
