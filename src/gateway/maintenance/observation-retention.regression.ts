import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { DEFAULT_RETENTION, runRetention, withRetainedRawRead, validateRetentionPolicy } from './observation-retention';
async function main() {
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'prom-retention-'));
  process.env.PROMETHEUS_DATA_DIR = path.join(temp, 'config');
  process.env.PROMETHEUS_WORKSPACE_DIR = path.join(temp, 'workspace');
  const raw = path.join(temp, 'raw'), now = Date.now();
  const put = async (name: string, days: number, size = 100) => {
    const file = path.join(raw, name); await fs.mkdir(path.dirname(file), { recursive: true });
    await fs.writeFile(file, 'x'.repeat(size)); const date = new Date(now - days * 86400000); await fs.utimes(file, date, date); return file;
  };
  const old = await put('session/old.txt', 40);
  const fresh = await put('session/recent.txt', 1);
  const active = await put('active/old.txt', 80);
  const summary = await put('session/summary.jsonl', 80);
  const reading = await put('session/reading.txt', 80);
  await withRetainedRawRead(reading, () => fs.readFile(reading, 'utf8'));
  const external = path.join(temp, 'outside'); await fs.mkdir(external); await fs.writeFile(path.join(external, 'keep.txt'), 'keep');
  await fs.symlink(external, path.join(raw, 'linked'), process.platform === 'win32' ? 'junction' : 'dir');
  const policy = { ...DEFAULT_RETENTION, enabled: true };
  const roots = [{ kind: 'observations' as const, path: raw, days: 30, maxBytes: 0, protectedDirectories: new Set(['active']) }];
  let ticks = 0; const ticker = setInterval(() => ticks++, 0);
  const preview = await runRetention(roots, policy, true, now);
  assert.equal(preview.eligible, 1); assert.equal(preview.eligibleBytes, 100); assert.equal(preview.removed, 0); await fs.access(old);
  const applied = await runRetention(roots, policy, false, now);
  assert.equal(applied.removed, 1); assert.equal(applied.reclaimedBytes, 100);
  assert.equal((await runRetention(roots, policy, false, now)).removed, 0);
  for (const file of [fresh, active, summary, reading, path.join(external, 'keep.txt')]) await fs.access(file);
  await assert.rejects(() => withRetainedRawRead(old, () => fs.readFile(old)), /expired or is unavailable/);
  await put('quota/a.txt', 9); await put('quota/b.txt', 8);
  const quota = await runRetention([{ ...roots[0], maxBytes: 50 }], policy, true, now);
  assert.ok(quota.eligible >= 2); assert.equal(quota.quotaUnmet, true, 'new/protected bodies can exceed soft quota');
  for (let i = 0; i < 600; i++) await put(`bulk/${i}.txt`, 80, 10);
  const batched = await runRetention(roots, { ...policy, maxDeletes: 7 }, false, now);
  assert.equal(batched.removed, 7); assert.ok(ticks > 0); clearInterval(ticker);
  assert.throws(() => validateRetentionPolicy({ enabled: 'true' }));
  assert.throws(() => validateRetentionPolicy({ rawDays: 1 }));
  assert.throws(() => validateRetentionPolicy({ surprise: true }));
  await assert.rejects(() => runRetention(roots, DEFAULT_RETENTION, false), /disabled/);
  const { readRetentionPolicy, writeRetentionPolicy, retentionPass } = await import('./retention-runtime');
  assert.equal((await readRetentionPolicy()).enabled, false);
  await writeRetentionPolicy({ ...DEFAULT_RETENTION, enabled: true }); assert.equal((await readRetentionPolicy()).enabled, true);
  await writeRetentionPolicy(DEFAULT_RETENTION); assert.equal((await readRetentionPolicy()).enabled, false);
  const { envelopeOversizedToolResult, readRawToolResultRange } = await import('../tool-result-envelope');
  const result = await envelopeOversizedToolResult({ name: 'fixture', args: {}, result: 'z'.repeat(70000), error: false }, { sessionId: 'fixture', toolName: 'fixture' });
  const ref = result.extra?.toolResultEnvelope?.rawRef;
  assert.equal((await readRawToolResultRange({ rawRef: ref, sessionId: 'fixture', maxChars: 256 })).content.length, 256);
  await assert.rejects(() => readRawToolResultRange({ rawRef: ref, sessionId: 'other' }), /current session/);
  const relative = ref.slice('tool-result-raw:'.length);
  await fs.unlink(path.join(process.env.PROMETHEUS_DATA_DIR!, 'tool-results', 'raw', relative));
  await assert.rejects(() => readRawToolResultRange({ rawRef: ref, sessionId: 'fixture' }), /expired/);
  assert.equal((await retentionPass(true)).report.removed, 0);
  console.log(JSON.stringify({ preview, applied, batched, eventLoopTicks: ticks }));
  console.log('PASS age/quota/active/recent/reader/junction/summary/dry-run/idempotence/batch/config/expiry');
}
main().then(() => process.exit(0), error => { console.error(error); process.exit(1); });
