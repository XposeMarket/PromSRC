/**
 * Writes a RUNNING minimal browser game into <project>/build/ that loads the
 * approved assets. The chat agent then edits build/game.js with normal file
 * tools to write the real game. assets.js/mp.js are regenerated on every
 * scaffold call; game.js/index.html are only written when missing unless
 * overwrite:true (so the agent's code is never clobbered).
 */
import fs from 'fs';
import path from 'path';
import { advanceStage, fromRel, gameDir, loadGame, mutateGame, type GameProject } from './project.js';

export const THREE_CDN = 'https://unpkg.com/three@0.160.0/build/three.module.js';

function manifest(ws: string, p: GameProject, buildDir: string) {
  const images: Record<string, string> = {};
  const audio: Record<string, string> = {};
  const copied: string[] = [];
  for (const a of p.assets) {
    if (a.status !== 'approved' || !a.path) continue;
    let src: string;
    try { src = fromRel(ws, a.path); } catch { continue; }
    if (!fs.existsSync(src)) continue;
    const isAudio = a.kind === 'sfx' || a.kind === 'music';
    const sub = isAudio ? 'audio' : 'assets';
    const name = `${a.name}${path.extname(src)}`;
    fs.mkdirSync(path.join(buildDir, sub), { recursive: true });
    fs.copyFileSync(src, path.join(buildDir, sub, name));
    (isAudio ? audio : images)[a.name] = `${sub}/${name}`;
    copied.push(`${sub}/${name}`);
  }
  return { images, audio, copied };
}

function assetsJs(images: Record<string, string>, audio: Record<string, string>): string {
  return `// Generated by Prometheus game_project scaffold. Regenerated on each scaffold call; do not hand-edit.
export const MANIFEST = ${JSON.stringify({ images, audio }, null, 2)};

/** Preload every image + audio file. Resolves { images: {name: HTMLImageElement}, audio: {name: HTMLAudioElement} }. */
export async function loadAssets(onProgress) {
  const entries = [...Object.entries(MANIFEST.images).map(([k, v]) => ['img', k, v]), ...Object.entries(MANIFEST.audio).map(([k, v]) => ['aud', k, v])];
  const out = { images: {}, audio: {} };
  let done = 0;
  await Promise.all(entries.map(([t, k, src]) => new Promise((resolve) => {
    const finish = () => { done++; if (onProgress) onProgress(done / Math.max(1, entries.length)); resolve(); };
    if (t === 'img') { const im = new Image(); im.onload = finish; im.onerror = finish; im.src = src; out.images[k] = im; }
    else { const a = new Audio(); a.preload = 'auto'; a.oncanplaythrough = finish; a.onerror = finish; a.src = src; out.audio[k] = a; setTimeout(finish, 3000); }
  })));
  return out;
}

/** Play a sound (clones so overlapping plays work). */
export function play(assets, name, volume = 0.6) {
  const a = assets && assets.audio && assets.audio[name];
  if (!a) return;
  try { const c = a.cloneNode(); c.volume = volume; c.play().catch(() => {}); } catch {}
}
`;
}

function mpJs(): string {
  return `// Multiplayer client for the Prometheus game room relay (SSE + POST).
// MP.connect(room) -> Promise<playerId>; MP.send(state); MP.on('state'|'join'|'leave'|'welcome', fn)
const handlers = {};
let base = '', playerId = '', es = null;
function emit(t, d) { (handlers[t] || []).forEach((fn) => { try { fn(d); } catch (e) { console.error(e); } }); }
function apiRoot() {
  const u = new URL(location.href);
  const i = u.pathname.indexOf('/api/game-projects/');
  return i >= 0 ? u.origin : (window.PROM_GATEWAY || u.origin);
}
export const MP = {
  get id() { return playerId; },
  on(type, fn) { (handlers[type] = handlers[type] || []).push(fn); return MP; },
  connect(room) {
    base = apiRoot() + '/api/game-rooms/' + encodeURIComponent(room || 'lobby');
    return new Promise((resolve, reject) => {
      es = new EventSource(base + '/events');
      es.onmessage = (ev) => {
        let m; try { m = JSON.parse(ev.data); } catch { return; }
        if (m.type === 'welcome') { playerId = m.playerId; emit('welcome', m); resolve(playerId); }
        else emit(m.type, m);
      };
      es.onerror = () => { if (!playerId) reject(new Error('room connect failed')); };
    });
  },
  send(state) {
    if (!playerId) return;
    fetch(base + '/send', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ playerId, type: 'state', data: state }) }).catch(() => {});
  },
  close() { if (es) es.close(); es = null; playerId = ''; },
};
window.MP = MP;
`;
}

