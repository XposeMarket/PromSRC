export async function writeScaffold(ws: string, projectId: string, args: { overwrite?: boolean } = {}): Promise<{ buildDir: string; files: string[]; copied: string[]; gameJs: string; kept: string[] }> {
  const p = loadGame(ws, projectId);
  const buildDir = path.join(gameDir(ws, projectId), 'build');
  fs.mkdirSync(buildDir, { recursive: true });
  const { images, audio, copied } = manifest(ws, p, buildDir);
  const files: string[] = [];
  const kept: string[] = [];
  const write = (name: string, content: string, always = false) => {
    const f = path.join(buildDir, name);
    if (!always && !args.overwrite && fs.existsSync(f)) { kept.push(name); return; }
    fs.writeFileSync(f, content);
    files.push(name);
  };
  write('assets.js', assetsJs(images, audio), true);
  if (p.design.multiplayer) write('mp.js', mpJs(), true);
  write('index.html', indexHtml(p));
  write('game.js', p.design.engine === 'three' ? threeGameJs(p) : canvasGameJs(p));
  await mutateGame(ws, projectId, (proj) => { advanceStage(proj, 'playable'); });
  const rel = path.relative(ws, path.join(buildDir, 'game.js')).split(path.sep).join('/');
  return { buildDir: path.relative(ws, buildDir).split(path.sep).join('/'), files, copied, gameJs: rel, kept };
}
