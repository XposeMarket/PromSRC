function canvasGameJs(p: GameProject): string {
  return `// ${p.title} — ${p.design.genre} / ${p.design.style}. Starter scaffold: REPLACE with the real game.
import { loadAssets, play } from './assets.js';
${p.design.multiplayer ? "import { MP } from './mp.js';\n" : ''}
const canvas = document.getElementById('game');
const ctx = canvas.getContext('2d');
const hud = document.getElementById('hud');
const W = 960, H = 540;
function fit() { const s = Math.min(innerWidth / W, innerHeight / H); canvas.width = W; canvas.height = H; canvas.style.width = (W * s) + 'px'; canvas.style.height = (H * s) + 'px'; canvas.style.margin = ((innerHeight - H * s) / 2) + 'px auto 0'; }
addEventListener('resize', fit); fit();
ctx.imageSmoothingEnabled = ${p.design.style === 'pixel' ? 'false' : 'true'};

const keys = new Set();
addEventListener('keydown', (e) => { keys.add(e.key.toLowerCase()); if (e.key === ' ') { play(assets, 'jump'); } });
addEventListener('keyup', (e) => keys.delete(e.key.toLowerCase()));
let touch = null;
canvas.addEventListener('pointerdown', (e) => { touch = { x: e.clientX, y: e.clientY }; play(assets, 'click'); });
canvas.addEventListener('pointermove', (e) => { if (touch) touch = { x: e.clientX, y: e.clientY }; });
addEventListener('pointerup', () => { touch = null; });

const player = { x: W / 2, y: H / 2, w: 64, h: 64, speed: 260 };
const others = new Map();
let assets = { images: {}, audio: {} };

function update(dt) {
  let dx = (keys.has('arrowright') || keys.has('d') ? 1 : 0) - (keys.has('arrowleft') || keys.has('a') ? 1 : 0);
  let dy = (keys.has('arrowdown') || keys.has('s') ? 1 : 0) - (keys.has('arrowup') || keys.has('w') ? 1 : 0);
  if (touch) { const r = canvas.getBoundingClientRect(); const tx = (touch.x - r.left) * W / r.width, ty = (touch.y - r.top) * H / r.height; dx = Math.sign(tx - player.x) * (Math.abs(tx - player.x) > 4 ? 1 : 0); dy = Math.sign(ty - player.y) * (Math.abs(ty - player.y) > 4 ? 1 : 0); }
  player.x = Math.max(player.w / 2, Math.min(W - player.w / 2, player.x + dx * player.speed * dt));
  player.y = Math.max(player.h / 2, Math.min(H - player.h / 2, player.y + dy * player.speed * dt));
}

function drawSprite(name, x, y, w, h, fallback) {
  const im = assets.images[name];
  if (im && im.complete && im.naturalWidth) ctx.drawImage(im, x - w / 2, y - h / 2, w, h);
  else { ctx.fillStyle = fallback; ctx.fillRect(x - w / 2, y - h / 2, w, h); }
}

function draw() {
  const bg = assets.images.background || Object.values(assets.images).find((i) => i.naturalWidth >= 512);
  if (bg && bg.naturalWidth) ctx.drawImage(bg, 0, 0, W, H); else { ctx.fillStyle = '#1b1b2b'; ctx.fillRect(0, 0, W, H); }
  for (const o of others.values()) drawSprite('player', o.x, o.y, player.w, player.h, '#4af');
  const heroName = assets.images.player ? 'player' : Object.keys(assets.images).find((k) => k !== 'background');
  drawSprite(heroName, player.x, player.y, player.w, player.h, '#fc3');
  hud.textContent = '${p.title.replace(/'/g, "\\'")} — arrows/WASD or touch to move, space to jump';
}

let last = performance.now();
function loop(now) {
  const dt = Math.min(0.05, (now - last) / 1000); last = now;
  update(dt); draw();
${p.design.multiplayer ? '  if (MP.id && Math.round(now / 50) % 2 === 0) MP.send({ x: player.x, y: player.y });\n' : ''}  requestAnimationFrame(loop);
}

assets = await loadAssets();
document.getElementById('loading').remove();
${p.design.multiplayer ? `MP.on('state', (m) => others.set(m.from, m.data)).on('leave', (m) => others.delete(m.playerId));
MP.connect(new URLSearchParams(location.search).get('room') || '${p.id}').catch((e) => console.warn(e));
` : ''}window.__game = { player, assets };
requestAnimationFrame(loop);
`;
}

