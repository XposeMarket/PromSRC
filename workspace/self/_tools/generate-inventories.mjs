#!/usr/bin/env node
// Regenerates self/generated/*.md from live source. Static scan only (no gateway needed).
// Usage: node self/_tools/generate-inventories.mjs [PROMSRC_PATH]
// Default PROMSRC_PATH: C:\Users\rafel\PromSRC  (override with arg or PROMSRC env)
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';

const selfDir = path.resolve(import.meta.dirname, '..');
const workspace = path.resolve(selfDir, '..');
const src = path.resolve(process.argv[2] || process.env.PROMSRC || 'C:\\Users\\rafel\\PromSRC');
const out = path.join(selfDir, 'generated');
fs.mkdirSync(out, { recursive: true });

const rel = (p) => path.relative(src, p).split(path.sep).join('/');
const read = (p) => { try { return fs.readFileSync(p, 'utf8'); } catch { return ''; } };
function walk(dir, filter, acc = []) {
  let ents = [];
  try { ents = fs.readdirSync(dir, { withFileTypes: true }); } catch { return acc; }
  for (const e of ents) {
    if (['node_modules', 'dist', '.git', 'vendor'].includes(e.name)) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, filter, acc); else if (filter(p)) acc.push(p);
  }
  return acc;
}
const isTs = (p) => /\.tsx?$/.test(p) && !/\.(regression|test|spec)\.tsx?$/.test(p) && !/\.d\.ts$/.test(p);
const oneLine = (s, n = 160) => (s || '').replace(/\\n/g, ' ').replace(/\s+/g, ' ').trim().slice(0, n).replace(/\|/g, '\\|');

let git = { head: 'unknown', date: '', branch: '' };
try {
  git.head = execSync('git rev-parse --short HEAD', { cwd: src }).toString().trim();
  git.date = execSync('git log -1 --format=%ci', { cwd: src }).toString().trim();
  git.branch = execSync('git rev-parse --abbrev-ref HEAD', { cwd: src }).toString().trim();
} catch {}
const stamp = `> GENERATED by \`self/_tools/generate-inventories.mjs\` — do not hand-edit; rerun instead.\n> Source: \`${src}\` @ \`${git.head}\` (${git.branch}, ${git.date}). Generated ${new Date().toISOString()}.\n`;
const write = (name, title, body) => fs.writeFileSync(path.join(out, name), `# ${title}\n\n${stamp}\n${body}\n`);

const tsFiles = walk(path.join(src, 'src'), isTs);

// ── 1. Tools: objects with name:'x' followed closely by description:'...'
const tools = new Map();
const toolRe = /name:\s*['"]([a-z][a-z0-9_]{2,})['"]\s*,\s*\n?\s*description:\s*(?:['"`])([\s\S]{0,400}?)(?:['"`]\s*[,+\n])/g;
for (const f of tsFiles) {
  const t = read(f);
  if (!t.includes('description')) continue;
  for (const m of t.matchAll(toolRe)) {
    const name = m[1];
    if (tools.has(name)) { tools.get(name).files.add(rel(f)); continue; }
    tools.set(name, { name, desc: oneLine(m[2]), files: new Set([rel(f)]) });
  }
}
// keep only tool-ish defs: in tools/ dirs, defs, connectors, or with "parameters" near
const toolRows = [...tools.values()]
  .filter((t) => [...t.files].some((f) => /tools|defs|connectors|integrations|extensions|tool-builder|creative|media|voice|browser|desktop|agents/.test(f)))
  .sort((a, b) => a.name.localeCompare(b.name));
const byPrefix = {};
for (const t of toolRows) (byPrefix[t.name.split('_')[0]] ||= []).push(t);
let tb = `Total tool-like definitions found: **${toolRows.length}**. Static scan of \`name: '…', description: '…'\` pairs; includes wrappers, connector tools, voice/desktop tools, and some internal schemas. The live per-turn surface is smaller (category-gated) — see \`../05-tools-and-categories.md\`.\n\n`;
tb += `Prefix groups: ${Object.entries(byPrefix).sort((a, b) => b[1].length - a[1].length).map(([k, v]) => `\`${k}_*\` ${v.length}`).join(', ')}\n\n`;
for (const [k, list] of Object.entries(byPrefix).sort()) {
  tb += `## ${k}\n\n| Tool | Description | Defined in |\n|---|---|---|\n`;
  for (const t of list) tb += `| \`${t.name}\` | ${t.desc} | ${[...t.files].slice(0, 2).map((f) => `\`${f}\``).join(', ')} |\n`;
  tb += '\n';
}
write('tools.md', 'Tool Inventory (generated)', tb);

// ── 2. Tool categories
const tb2Src = read(path.join(src, 'src/gateway/tool-builder.ts'));
const pcSrc = read(path.join(src, 'src/gateway/prompt-context.ts'));
let cat = '';
const idsM = tb2Src.match(/TOOL_CATEGORY_IDS\s*=\s*\[([\s\S]*?)\]/) || read(path.join(src, 'src/gateway/tool-builder.ts')).match(/CATEGORY_IDS[^=]*=\s*\[([\s\S]*?)\]/);
if (idsM) cat += `Category IDs (tool-builder): ${[...idsM[1].matchAll(/['"]([a-z_]+)['"]/g)].map((m) => `\`${m[1]}\``).join(', ')}\n\n`;
const polM = pcSrc.match(/CATEGORY_POLICIES[^{]*\{([\s\S]*?)\n\};/);
if (polM) {
  cat += `## CATEGORY_POLICIES (src/gateway/prompt-context.ts)\n\n| Category | Policy |\n|---|---|\n`;
  for (const m of polM[1].matchAll(/^\s*['"]?([a-z_]+)['"]?\s*:\s*[`'"]([\s\S]*?)[`'"],?\s*$/gm)) cat += `| \`${m[1]}\` | ${oneLine(m[2], 300)} |\n`;
}
if (!cat) cat = 'Could not locate TOOL_CATEGORY_IDS / CATEGORY_POLICIES — check src/gateway/tool-builder.ts and prompt-context.ts.';
write('tool-categories.md', 'Tool Categories (generated)', cat);

// ── 3. HTTP routes
const routes = [];
const routeRe = /\b(router|app|r)\.(get|post|put|patch|delete|all)\(\s*['"`]([^'"`]+)['"`]/g;
for (const f of tsFiles.filter((f) => f.includes(`${path.sep}gateway${path.sep}`) || f.includes('server'))) {
  const t = read(f);
  for (const m of t.matchAll(routeRe)) routes.push({ method: m[2].toUpperCase(), path: m[3], file: rel(f) });
}
routes.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
const byFile = {};
for (const r of routes) (byFile[r.file] ||= []).push(r);
let rb = `Total routes: **${routes.length}** across ${Object.keys(byFile).length} files.\n\n`;
for (const [f, list] of Object.entries(byFile).sort()) {
  rb += `## \`${f}\` (${list.length})\n\n`;
  rb += list.map((r) => `- \`${r.method} ${r.path}\``).join('\n') + '\n\n';
}
write('routes.md', 'HTTP Route Inventory (generated)', rb);

// ── 4. Connectors / MCP presets / provider extensions
let cb = '';
for (const kind of ['connectors', 'mcp_presets', 'providers']) {
  const dir = path.join(src, 'src/extensions/bundled', kind);
  const manifests = walk(dir, (p) => /manifest.*\.json$|\.json$/.test(p) && !p.includes('package'));
  const rows = [];
  for (const m of manifests) {
    let j; try { j = JSON.parse(read(m)); } catch { continue; }
    if (!j.id) continue;
    const tools = j.ownership?.tools || [];
    const toolNames = tools.map((t) => (typeof t === 'string' ? t : t.name)).filter(Boolean);
    rows.push({ id: j.id, name: j.name || j.id, cat: j.category || '', tools: toolNames, api: toolNames.some((n) => /api_request/.test(n)), file: rel(m) });
  }
  rows.sort((a, b) => a.id.localeCompare(b.id));
  cb += `## ${kind} (${rows.length})\n\n| id | Name | Category | Tools | api_request escape hatch | Manifest |\n|---|---|---|---|---|---|\n`;
  for (const r of rows) cb += `| \`${r.id}\` | ${oneLine(r.name, 40)} | ${r.cat} | ${r.tools.length ? r.tools.length + ': ' + r.tools.slice(0, 30).map((t) => `\`${t}\``).join(' ') : '—'} | ${kind === 'connectors' ? (r.api ? '✅' : '❌ GAP') : ''} | \`${r.file}\` |\n`;
  cb += '\n';
}
cb += `Rule (USER.md, 2026-09-28): every connector must expose full capability plus an approval-gated \`<connector>_api_request\`. Any ❌ GAP above is a fix-PR, not a question.\n`;
write('connectors.md', 'Connector / MCP Preset / Provider Extension Inventory (generated)', cb);

// ── 5. Skills
const skillsDir = path.join(workspace, 'skills');
const skillRows = [];
for (const d of fs.existsSync(skillsDir) ? fs.readdirSync(skillsDir, { withFileTypes: true }) : []) {
  if (!d.isDirectory()) continue;
  const md = read(path.join(skillsDir, d.name, 'SKILL.md'));
  if (!md) continue;
  const fm = (md.match(/^---\n([\s\S]*?)\n---/) || [])[1] || '';
  const desc = (fm.match(/^description:\s*(.+)$/m) || [])[1] || (md.replace(/^---[\s\S]*?---/, '').match(/\n([^#\n][^\n]{20,})/) || [])[1] || '';
  skillRows.push({ id: d.name, desc: oneLine(desc.replace(/^["']|["']$/g, ''), 200), size: md.length });
}
skillRows.sort((a, b) => a.id.localeCompare(b.id));
write('skills.md', 'Installed Skills (generated)', `Total: **${skillRows.length}** in \`workspace/skills/\`. Read with \`skill_read(id)\`; discover with \`skill_list(query)\`.\n\n| id | Description | Size |\n|---|---|---|\n` + skillRows.map((s) => `| \`${s.id}\` | ${s.desc} | ${Math.round(s.size / 1024)}KB |`).join('\n'));

// ── 6. Source map: dirs + file counts + largest files
let sb = '| Dir | TS files | KB |\n|---|---|---|\n';
const dirStats = {};
for (const f of walk(path.join(src, 'src'), (p) => /\.tsx?$/.test(p))) {
  const parts = rel(f).split('/');
  const key = parts[1] === 'gateway' && parts.length > 3 ? `src/gateway/${parts[2]}` : parts.slice(0, 2).join('/');
  const s = (dirStats[key] ||= { n: 0, kb: 0 });
  s.n++; s.kb += fs.statSync(f).size / 1024;
}
for (const [k, v] of Object.entries(dirStats).sort()) sb += `| \`${k}\` | ${v.n} | ${Math.round(v.kb)} |\n`;
const big = walk(path.join(src, 'src'), isTs).map((f) => ({ f: rel(f), kb: fs.statSync(f).size / 1024 })).sort((a, b) => b.kb - a.kb).slice(0, 30);
sb += `\n## Largest source files (edit with care — grep, then read windows)\n\n| File | KB |\n|---|---|\n` + big.map((b) => `| \`${b.f}\` | ${Math.round(b.kb)} |`).join('\n');
const webui = walk(path.join(src, 'web-ui/src'), (p) => /\.(js|ts|tsx|jsx|css|html)$/.test(p));
const wdirs = {};
for (const f of webui) { const k = rel(f).split('/').slice(0, 3).join('/'); wdirs[k] = (wdirs[k] || 0) + 1; }
sb += `\n\n## web-ui/src\n\n` + Object.entries(wdirs).sort().map(([k, v]) => `- \`${k}\` — ${v} files`).join('\n');
write('source-map.md', 'Source Map (generated)', sb);

// ── 7. Recent merged PRs (changelog)
let log = '';
try {
  log = execSync('git log --since=2026-08-01 --first-parent --format="%h|%cs|%s" -n 600', { cwd: src }).toString().trim().split('\n')
    .filter((l) => /#\d+/.test(l)).map((l) => { const [h, d, ...s] = l.split('|'); return `- \`${h}\` ${d} — ${oneLine(s.join('|'), 140)}`; }).join('\n');
} catch {}
write('changelog.md', 'Merged PR Changelog since 2026-08-01 (generated)', log || 'git log unavailable');

// ── 8. Regression/test scripts
const tests = walk(path.join(src, 'scripts'), (p) => /test-.*\.(mjs|ts|js)$/.test(p)).map(rel).sort();
const regs = walk(path.join(src, 'src'), (p) => /\.regression\.tsx?$/.test(p)).map(rel).sort();
write('tests.md', 'Test & Regression Inventory (generated)', `scripts/test-*: **${tests.length}**, src/**/*.regression.ts: **${regs.length}**. Grep this list for the subsystem you touched and run the matching files.\n\n## scripts\n\n${tests.map((t) => `- \`${t}\``).join('\n')}\n\n## regression files\n\n${regs.map((t) => `- \`${t}\``).join('\n')}`);

console.log(JSON.stringify({ head: git.head, tools: toolRows.length, routes: routes.length, skills: skillRows.length, tests: tests.length, regressions: regs.length, out }, null, 0));
