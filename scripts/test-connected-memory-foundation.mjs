import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { spawnSync } from 'node:child_process';
const require = createRequire(import.meta.url);
require('tsx/cjs');
const { ResourceStore } = require('../src/gateway/resources/resource-store.ts');
const { ReferenceStore, readReferencePins, AUTOMATIC_REFERENCE_CAPTURE_READY } = require('../src/gateway/resources/reference-store.ts');
const { ReferenceService } = require('../src/gateway/resources/reference-service.ts');
const { createAnalysisRun, hashFile, preserveAnalysisArtifacts } = require('../src/gateway/resources/analysis-artifacts.ts');
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'connected-memory-'));
const workspace = path.join(temp, 'workspace');
const rootDir = path.join(temp, 'resources');
fs.mkdirSync(workspace, { recursive: true });
let metadata;
let resources;
try {
  assert.equal(AUTOMATIC_REFERENCE_CAPTURE_READY, false);
  assert.equal(fs.existsSync(rootDir), false, 'imports do not create an archive');
  resources = new ResourceStore({ rootDir, workspacePath: workspace, configDir: temp });
  metadata = new ReferenceStore(rootDir, workspace);
  const service = new ReferenceService(resources, metadata);
  const addVersion = content => resources.attach({ kind: 'file', title: 'Reference', origin: 'user_upload', locator: { type: 'file', canonical: 'fixture.txt' }, content, snapshotKind: 'text' });
  const first = addVersion('version 1');
  const binding = { resourceId: first.resource.id, versionId: first.version.id };
  const saved = service.saveExisting({ operationId: 'fixture-save', binding, title: 'Office lighting', userQuote: 'This is the lighting I want' });
  assert.equal(saved.userQuote, 'This is the lighting I want');
  for (let i = 2; i <= 26; i++) addVersion(`version ${i}`);
  resources.flushSync();
  assert.ok(resources.referenceVersion(binding.resourceId, binding.versionId), 'pinned v1 survives 26 versions');
  assert.ok(readReferencePins(rootDir).has(binding.versionId));
  assert.equal(service.saveExisting({ operationId: 'fixture-save', binding, title: 'retry' }).id, saved.id);
  const second = new ReferenceStore(rootDir, workspace);
  assert.equal(second.writable, false);
  assert.equal(second.get(saved.id).id, saved.id);
  assert.throws(() => second.prepare(saved, [binding]), /read-only/);
  second.close();
  const child = spawnSync(process.execPath, ['-e', `require('tsx/cjs');const {ReferenceStore}=require('./src/gateway/resources/reference-store.ts');const s=new ReferenceStore(process.argv[1],process.argv[2]);if(s.writable)process.exit(3);try{s.assertWriter();process.exit(4)}catch{}s.close();` , rootDir, workspace], { cwd: process.cwd(), encoding: 'utf8' });
  assert.equal(child.status, 0, child.stderr);
  const privateReader = new ReferenceStore(rootDir, path.join(temp, 'other'), { readOnly: true });
  assert.equal(privateReader.get(saved.id), undefined);
  privateReader.close();
  const scopedWriter = new ReferenceStore(rootDir, path.join(temp, 'other'), { owner: metadata });
  assert.equal(scopedWriter.writable, true, 'same gateway shares one writer across workspaces');
  assert.equal(scopedWriter.get(saved.id), undefined);
  scopedWriter.close(); metadata.assertWriter();
  console.log('PASS retention, idempotency, second writer and workspace scope');

  const pending = { ...saved, id: 'ref_pending', operationId: 'pending', createdAt: new Date().toISOString() };
  metadata.prepare(pending, [binding]);
  metadata.close();
  metadata = new ReferenceStore(rootDir, workspace);
  assert.equal(metadata.recover(b => Boolean(resources.referenceVersion(b.resourceId, b.versionId))).completed, 1);
  assert.equal(metadata.get('ref_pending').operationId, 'pending');
  const absent = { ...pending, id: 'ref_absent', operationId: 'absent', versionId: 'ver_missing' };
  metadata.prepare(absent, [{ resourceId: absent.resourceId, versionId: absent.versionId }]);
  assert.equal(metadata.recover(() => false).pending, 1);
  assert.ok(metadata.pins().has('ver_missing'), 'pending age cannot delete roots');
  const backup = path.join(temp, 'metadata-backup.sqlite');
  await metadata.backup(backup);
  const Database = require('better-sqlite3');
  const backupDb = new Database(backup, { readonly: true });
  assert.equal(backupDb.prepare('SELECT COUNT(*) AS n FROM saved_references').get().n, 2);
  backupDb.close();
  const crashRoot = path.join(temp, 'crash-resources');
  const crash = spawnSync(process.execPath, ['-e', `require('tsx/cjs');const {ReferenceStore}=require('./src/gateway/resources/reference-store.ts');new ReferenceStore(process.argv[1],process.argv[2]);process.exit(0);`, crashRoot, workspace], { cwd: process.cwd(), encoding: 'utf8' });
  assert.equal(crash.status, 0, crash.stderr);
  const recoveredWriter = new ReferenceStore(crashRoot, workspace);
  assert.equal(recoveredWriter.writable, true, 'provably dead process lock is recovered');
  recoveredWriter.close();
  console.log('PASS interrupted metadata recovery, SQLite backup, dead-process lock recovery; missing evidence stays pending');

  const sourcePath = path.join(workspace, 'clip.mp4'); fs.writeFileSync(sourcePath, 'synthetic-video');
  const a = createAnalysisRun(workspace, 'downloads/video_analysis/clip');
  const b = createAnalysisRun(workspace, 'downloads/video_analysis/clip');
  assert.notEqual(a.directory, b.directory);
  const frame = path.join(a.directory, 'frame.jpg'); fs.writeFileSync(frame, 'synthetic-frame');
  const input = { workspace, directory: a.directory, runId: a.id, sourcePath, sourceHash: await hashFile(sourcePath), frames: [{ path: frame, timestampSeconds: 1.25 }], contactSheets: [], transcript: 'existing speech', transcriptionProvider: 'fixture', analysisPrompt: 'Look at menu movement', observationMode: 'report' };
  await preserveAnalysisArtifacts({ ...input, status: 'extracted' });
  const result = await preserveAnalysisArtifacts({ ...input, status: 'complete', analysis: 'A sampled frame, not continuous motion.' });
  assert.equal(result.manifest.files[0].timestampSeconds, 1.25);
  assert.equal(result.manifest.coverage, 'sampled_frames');
  assert.equal(result.manifest.transcript.text, 'existing speech');
  await assert.rejects(preserveAnalysisArtifacts({ ...input, status: 'complete' }), /EEXIST/);
  assert.throws(() => createAnalysisRun(workspace, '../outside'), /unsafe|escaped|relative|traversal/i);
  const c = createAnalysisRun(workspace, 'downloads/video_analysis/clip');
  await assert.rejects(preserveAnalysisArtifacts({ ...input, directory: c.directory, runId: c.id, status: 'complete' }), /unsafe|escaped|relative|traversal/i);
  const service2 = new ReferenceService(resources, metadata);
  const analysisRef = service2.saveAnalysis({ operationId: 'analysis-fixture', manifestPath: path.relative(workspace, result.path) });
  const analysisVersion = resources.referenceVersion(analysisRef.resourceId, analysisRef.versionId);
  const archivedManifest = JSON.parse(fs.readFileSync(path.join(rootDir, analysisVersion.snapshotPath), 'utf8'));
  assert.equal(archivedManifest.files[0].pathRoot, 'resources');
  fs.unlinkSync(frame);
  assert.equal(fs.readFileSync(path.join(rootDir, archivedManifest.files[0].path), 'utf8'), 'synthetic-frame');
  assert.ok(metadata.pins().has(archivedManifest.sourceBinding.versionId));
  assert.equal(service2.saveAnalysis({ operationId: 'analysis-fixture', manifestPath: 'no-longer-needed' }).id, analysisRef.id);
  console.log('PASS immutable manifests, timestamps, traversal rejection, real artifact archive and original retention');

  metadata.close(); metadata = undefined;
  fs.renameSync(path.join(rootDir, 'references.sqlite'), path.join(rootDir, 'references.sqlite.backup'));
  assert.throws(() => readReferencePins(rootDir), /missing/);
  assert.throws(() => new ReferenceStore(rootDir, workspace), /missing/);
  const kept = addVersion('before missing metadata');
  for (let i = 0; i < 26; i++) addVersion(`later ${i}`);
  resources.flushSync();
  assert.ok(resources.referenceVersion(kept.resource.id, kept.version.id), 'metadata outage disables pruning');
  console.log('PASS metadata loss fails closed without blocking existing attachments');
  console.log('CONNECTED_MEMORY_FOUNDATION_PASS');
} finally {
  resources?.flushSync(); metadata?.close();
  await new Promise(resolve => setTimeout(resolve, 30));
  fs.rmSync(temp, { recursive: true, force: true });
}
