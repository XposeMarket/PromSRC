import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url); require('tsx/cjs');
const { ResourceStore } = require('../src/gateway/resources/resource-store.ts');
const { ReferenceStore } = require('../src/gateway/resources/reference-store.ts');
const { ReferenceService } = require('../src/gateway/resources/reference-service.ts');
const { openReference, assertPersonalReferenceCaller, publicReference } = require('../src/gateway/resources/reference-library.ts');
const { runWithRuntimeActorContext } = require('../src/gateway/runtime-actor.ts');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'reference-library-'));
const workspace = path.join(root, 'workspace'); fs.mkdirSync(workspace);
const resources = new ResourceStore({ rootDir: path.join(root, 'resources'), workspacePath: workspace, configDir: root });
const metadata = new ReferenceStore(resources.rootDir, workspace); const service = new ReferenceService(resources, metadata);
try {
  assert.deepEqual(metadata.settings(), { capture: false, recall: false });
  assert.deepEqual(metadata.setSettings({ capture: true }), { capture: true, recall: false });
  const note = service.saveText({ operationId: 'office-note', title: 'Office lighting', content: 'Warm lamps and indirect light', userQuote: 'This is the lighting I want', sourceSession: 'old-chat' });
  assert.equal(metadata.list({ query: 'warm' })[0].id, note.id);
  assert.equal(openReference(service, note.id).text, 'Warm lamps and indirect light');
  assert.equal(publicReference(note).workspace, undefined);
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a1N8AAAAASUVORK5CYII=', 'base64');
  const imagePath = path.join(workspace, 'office.png'); fs.writeFileSync(imagePath, png);
  const photo = service.saveAttachment({ operationId: 'photo', filePath: imagePath, mimeType: 'image/png', title: 'Office photo', userQuote: 'My preferred lighting' });
  fs.unlinkSync(imagePath);
  assert.deepEqual(openReference(service, photo.id).assets[0].bytes, png, 'opens preserved bytes after source removed');
  assert.throws(() => openReference(service, photo.id, { versionId: 'wrong' }), /version/);
  metadata.update(photo.id, { relatedIds: [note.id], interpretation: 'Warm indirect lighting', status: 'confirmed' });
  assert.equal(metadata.get(photo.id).relatedIds[0], note.id);
  assert.equal(metadata.backlinks(note.id)[0].id, photo.id);
  assert.ok(metadata.storageUsage() > 0);
  metadata.forgetSource(note.id); assert.ok(metadata.forgottenSessions().has('old-chat'));
  metadata.update(note.id, { excluded: false }); assert.equal(metadata.forgottenSessions().size, 0);
  const zip = await require('../src/gateway/resources/reference-library.ts').exportReference(service, photo.id);
  const archive = await require('jszip').loadAsync(zip); assert.deepEqual(await archive.file('original.png').async('nodebuffer'), png);
  metadata.update(photo.id, { excluded: true });
  assert.throws(() => service.saveExisting({ operationId: 'excluded-new-operation', title: 'retry', binding: { resourceId: photo.resourceId, versionId: photo.versionId } }), /excluded/);
  assert.equal(metadata.list({ query: 'photo' }).length, 0);
  assert.throws(() => openReference(service, photo.id), /excluded/);
  assert.equal(openReference(service, photo.id, { owner: true }).assets.length, 1);
  metadata.update(photo.id, { excluded: false });
  const otherWorkspace = path.join(root, 'other'); fs.mkdirSync(otherWorkspace);
  const other = new ReferenceStore(resources.rootDir, otherWorkspace, { owner: metadata });
  assert.equal(other.get(photo.id), undefined); assert.equal(other.list().length, 0);
  assert.throws(() => assertPersonalReferenceCaller('background_private'), /not granted/);
  metadata.remove(photo.id); assert.throws(() => openReference(service, photo.id, { owner: true }), /unavailable/);
  assert.equal(service.saveAttachment({ operationId: 'photo', filePath: 'missing' }).deleted, true, 'deleted operation cannot resurrect');
  const corrupt = resources.referenceVersion(note.resourceId, note.versionId);
  fs.appendFileSync(path.join(resources.rootDir, corrupt.snapshotPath), 'tamper');
  assert.throws(() => openReference(service, note.id), /integrity/);
  assert.throws(() => openReference(service, '../registry.json'), /unavailable/);
  console.log('CONNECTED_MEMORY_LIBRARY_PASS: save/find/open, originals survive, correction/links, exclusion/delete, scope, integrity');
} finally { resources.flushSync(); metadata.close(); fs.rmSync(root, { recursive: true, force: true }); }
