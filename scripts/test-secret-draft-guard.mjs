import assert from 'node:assert/strict';
import fs from 'node:fs';
import { containsRecognizableSecret, removeRecognizableSecrets, assertSafeChatRequest } from '../web-ui/src/features/chat/secret-format-guard.js';
import { saveComposerDraft, readComposerDraft } from '../web-ui/src/features/chat/composer-drafts.js';
const storage = new Map();
globalThis.localStorage = { getItem: key => storage.get(key) || null, setItem: (key, value) => storage.set(key, value), removeItem: key => storage.delete(key) };
const secret = 'ghp_' + 'a'.repeat(36);
assert(containsRecognizableSecret(secret));
assert(!removeRecognizableSecrets(secret).includes(secret));
saveComposerDraft('fixture', `hello ${secret}`);
assert(!JSON.stringify([...storage]).includes(secret));
assert.equal(readComposerDraft('fixture'), 'hello [secret removed]');
for (const route of ['/api/chat', '/api/chat/steer', '/api/sessions/fixture/history', '/api/sessions/fixture/edit-rerun-reset']) assert.throws(() => assertSafeChatRequest(route, JSON.stringify({ message: secret })));
assert.doesNotThrow(() => assertSafeChatRequest('/api/auth/x-api/credentials', JSON.stringify({ clientSecret: secret })));
assert.doesNotThrow(() => assertSafeChatRequest('/api/chat', JSON.stringify({ message: 'example placeholder API_KEY' })));
const src = fs.readFileSync('src/security/secret-format-guard.ts', 'utf8');
const ui = fs.readFileSync('web-ui/src/features/chat/secret-format-guard.js', 'utf8');
assert.equal(src.match(/const SOURCES = \[([\s\S]*?)\];/)[1], ui.match(/const SOURCES = \[([\s\S]*?)\];/)[1]);
console.log('PASS draft/send guard: no raw persisted key, matching backend/client formats, chat/history/edit blocked, protected routes unaffected.');
