import assert from 'node:assert/strict';
import { parseHTML } from 'linkedom';
import { reconcileKeyedTimelineRows, swapKeyedTimelineSession } from '../web-ui/src/features/chat/timeline/keyed-dom.js';
const { document } = parseHTML('<!doctype html><html><body><div id="thread"></div></body></html>');
const root = document.getElementById('thread');
const rows = (sid, n) => Array.from({ length: n }, (_, i) => `<div data-chat-row-key="${sid}-${i}" data-chat-row-signature="s${i}">${sid} ${i}</div>`).join('');
swapKeyedTimelineSession(root, 'A', { namespace: 't' });
reconcileKeyedTimelineRows(root, rows('A', 3));
const liveToolNode = root.children[2];
liveToolNode.setAttribute('data-live-marker', 'kept');
assert.equal(swapKeyedTimelineSession(root, 'B', { namespace: 't' }), false, 'first visit to B has nothing cached');
assert.equal(root.children.length, 0, 'A rows are parked, not left in B');
reconcileKeyedTimelineRows(root, rows('B', 2));
assert.equal(swapKeyedTimelineSession(root, 'A', { namespace: 't' }), true, 'returning to A restores parked rows');
assert.equal(root.children[2], liveToolNode, 'the exact live row node survives the round trip');
const stats = reconcileKeyedTimelineRows(root, rows('A', 4));
assert.equal(stats.created, 1, 'only the row added while away is created');
assert.equal(root.children[2].getAttribute('data-live-marker'), 'kept', 'no rebuild of existing rows');
assert.equal(swapKeyedTimelineSession(root, 'A', { namespace: 't' }), false, 'same-session render is a no-op');
const fresh = document.createElement('div');
document.body.appendChild(fresh);
root.remove();
swapKeyedTimelineSession(fresh, 'B', { namespace: 't' });
assert.equal(fresh.children.length, 2, 'B restored into a rebuilt container');
assert.equal(swapKeyedTimelineSession(fresh, 'A', { namespace: 't' }), true, 'A rescued from the detached old container');
assert.equal(fresh.children.length, 4);
console.log('PASS keyed timeline session swap keeps live rows across thread switches');
