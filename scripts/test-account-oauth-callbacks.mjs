import assert from 'node:assert/strict';
const {awaitGatewayOAuthCallback,completeGatewayOAuthCallback,cancelGatewayOAuthCallback,hasPendingGatewayOAuth}=await import('../dist/integrations/gateway-oauth-callback.js');
const called=[];
const a=awaitGatewayOAuthCallback('fixture:a',10000,async()=>{called.push('a');return {success:true};},{serviceId:'fixture',expectedState:'state-a'});
const b=awaitGatewayOAuthCallback('fixture:b',10000,async()=>{called.push('b');return {success:true};},{serviceId:'fixture',expectedState:'state-b'});
assert.equal(await completeGatewayOAuthCallback('fixture',{code:'fake',state:'wrong'}),null);
assert.deepEqual(called,[]);
assert.equal((await completeGatewayOAuthCallback('fixture',{code:'fake',state:'state-b'})).success,true);
assert.equal((await b).success,true);
assert.deepEqual(called,['b']);
assert.equal(hasPendingGatewayOAuth('fixture'),true);
cancelGatewayOAuthCallback('fixture:a');
assert.equal((await a).success,false);
assert.equal(hasPendingGatewayOAuth('fixture'),false);
assert.equal(await completeGatewayOAuthCallback('fixture',{code:'fake',state:'state-a'}),null);
const legacy=awaitGatewayOAuthCallback('legacy-fixture',10000,async()=>({success:true}));
assert.equal((await completeGatewayOAuthCallback('legacy-fixture',{code:'fake',state:'legacy'})).success,true);
assert.equal((await legacy).success,true);
console.log('PASS concurrent account callback routing, wrong-state preservation, sibling cancel and legacy compatibility');
let finish; let count=0;
const waiting=awaitGatewayOAuthCallback('race:a',10000,async()=>{count++;return await new Promise(resolve=>{finish=()=>resolve({success:true});});},{serviceId:'race',expectedState:'race-state'});
const first=completeGatewayOAuthCallback('race',{code:'fake',state:'race-state'});
assert.equal((await completeGatewayOAuthCallback('race',{code:'fake',state:'race-state'})).success,false);
assert.equal(count,1); finish(); await first; await waiting;
console.log('PASS duplicate callback cannot execute token exchange twice');
