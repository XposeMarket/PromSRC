// Generates src/gateway/prom-viz-reference.ts from the HELP block in prom-viz.js so the
// model's Viz Kit reference can never drift from the kit. `--check` exits 1 when stale.
import { readFileSync, writeFileSync } from 'node:fs';
const kitUrl = new URL('../web-ui/vendor/prom-viz/prom-viz.js', import.meta.url);
const outUrl = new URL('../src/gateway/prom-viz-reference.ts', import.meta.url);
const kit = readFileSync(kitUrl, 'utf8');
const m = kit.match(/\/\*HELP_START\*\/([\s\S]*?)\/\*HELP_END\*\//);
if (!m) { console.error('HELP markers not found in prom-viz.js'); process.exit(1); }
const help = JSON.parse(m[1]);
const lines = Object.values(help).map((e) => e.sig);
const body = `// GENERATED by scripts/gen-prom-viz-reference.mjs from web-ui/vendor/prom-viz/prom-viz.js HELP. Do not edit.
export const PROM_VIZ_SIGNATURES: readonly string[] = ${JSON.stringify(lines, null, 2)};

export const PROM_VIZ_REFERENCE =
  'Viz Kit exact call shapes (t = target element or null for the page root; never pass bare arrays except to ui.kpis; ui.help(name) returns {sig, ex} at runtime): ' +
  PROM_VIZ_SIGNATURES.join('; ') + '.';
`;
const current = (() => { try { return readFileSync(outUrl, 'utf8'); } catch { return ''; } })();
if (process.argv.includes('--check')) {
  if (current !== body) { console.error('FAIL prom-viz-reference.ts is stale: run node scripts/gen-prom-viz-reference.mjs'); process.exit(1); }
  console.log('PASS prom-viz reference in sync (' + lines.length + ' entries)');
} else {
  writeFileSync(outUrl, body);
  console.log('wrote prom-viz-reference.ts (' + lines.length + ' entries)');
}
