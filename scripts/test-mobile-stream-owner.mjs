import assert from 'node:assert/strict';
import fs from 'node:fs';
import { mobileStreamOwner, rememberMobileStreamOwner } from '../web-ui/src/mobile/mobile-stream-owner.js';

const source = fs.readFileSync(new URL('../web-ui/src/mobile/mobile-pages.js', import.meta.url), 'utf8');
const start = source.indexOf("    case '_mobileStreamTargetTurn': {");
const end = source.indexOf("    case '_findMobileRecoverableAssistantTurn':", start);
assert.ok(start >= 0 && end > start);
const resolve = new Function('__pmChat', 'mobileStreamOwner', 'turn', `const args = [turn]; switch ('_mobileStreamTargetTurn') { ${source.slice(start, end)} }`);
const continuation = () => ({ role: 'ai', workflowPart: 'interruption_response', streaming: true });
const a = continuation();
const b = continuation();
const chat = { activeSessionId: 'b', threads: { a: [a], b: [b] } };
const unknown = { role: 'ai' };
assert.equal(resolve(chat, mobileStreamOwner, unknown), unknown, 'detached unknown owner does not target active chat B');
const original = { role: 'ai' };
rememberMobileStreamOwner(original, 'a');
rememberMobileStreamOwner(original, 'b');
assert.equal(mobileStreamOwner(original, chat.threads), 'a', 'stream-start ownership is immutable');
assert.equal(resolve(chat, mobileStreamOwner, original), a, 'known owner still targets A after snapshot replacement');
assert.notEqual(resolve(chat, mobileStreamOwner, original), b);
const attached = { role: 'ai' };
chat.threads.a = [attached];
assert.equal(mobileStreamOwner(attached, chat.threads), 'a');
chat.threads.a = [continuation()];
assert.equal(resolve(chat, mobileStreamOwner, attached), chat.threads.a[0], 'inferred owner survives detached row');
const runtime = fs.readFileSync(new URL('../web-ui/src/mobile/mobile-chat-page-runtime.js', import.meta.url), 'utf8');
assert.match(runtime, /rememberMobileStreamOwner\(aiTurn, actualSessionId\);\s*activeThread.push\(aiTurn\)/, 'owner captured before stream starts');
console.log('mobile stream owner regression passed');
