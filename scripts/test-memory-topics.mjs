import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { memoryTopics, normalizeMemoryTopic, loadMemoryTopicIndex, expandMemoryTopics, readRelatedMemory, tagKnownMemoryTopics, memoryTopicPointers } from '../src/gateway/memory-index/memory-topics.ts';
import { retrieveHybridMemoryAtoms, clearHybridMemoryAtomCache } from '../src/gateway/memory-index/memory-atoms-hybrid.ts';
import { formatMemoryAtomReferenceContext } from '../src/gateway/memory-index/memory-atoms.ts';
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'memory-topics-'));
const other = fs.mkdtempSync(path.join(os.tmpdir(), 'memory-topics-other-'));
const raw = '# Memory\n## facts\n- Quasar release calendar freezes September 12. [[Rockfall Relay]]\n- Amber badges cost seven tokens. [[rockfall relay]] [[Side Quest]]\n- Penguins eat frozen fish. [[Side Quest]]\n- Violet ribbons unlock tomorrow. [[Rockfall Relay]]\n- [superseded] OBSOLETE secret. [[Rockfall Relay]]\n- [memory-status:untrusted] EVIL secret. [[Rockfall Relay]]\n';
try {
  assert.deepEqual(memoryTopics('[[ Rockfall   Relay ]] [[rockfall relay]] [[../bad]] [[x\ny]]'), ['rockfall relay']);
  assert.equal(normalizeMemoryTopic('x'.repeat(81)), '');
  fs.writeFileSync(path.join(root, 'MEMORY.md'), raw);
  const index = loadMemoryTopicIndex(root);
  assert.equal(index.byTopic.get('rockfall relay').length, 3);
  const anchor = { atom: index.atoms[0], score: 0.8, matchedTerms: [], relation: 'direct' };
  const related = expandMemoryTopics(index, [anchor], new Set([anchor.atom.id]));
  assert.equal(related.length, 2);
  assert(!related.some(m => m.atom.rawText.includes('Penguins')), 'must not expand two hops');
  assert.equal(expandMemoryTopics(index, [{ ...anchor, score: 0.2 }], new Set()).length, 0);
  assert.equal(memoryTopicPointers(index, [anchor])[0].remaining, 2);
  assert.match(readRelatedMemory(root, '[[ROCKFALL RELAY]]', 1), /Shown 1; remaining 2/);
  assert(!readRelatedMemory(root, 'rockfall relay').includes('EVIL'));
  assert.match(readRelatedMemory(other, 'rockfall relay'), /0 linked facts/);
  assert.match(tagKnownMemoryTopics('Rockfall Relay has a new zone.', raw), /\[\[rockfall relay\]\]/);
  assert.equal(tagKnownMemoryTopics('NotRockfall Relayish', raw), 'NotRockfall Relayish');
  assert.equal(tagKnownMemoryTopics('A different game', raw), 'A different game');
  assert.equal(memoryTopics(tagKnownMemoryTopics('[[Rockfall Relay]] is ready', raw)).length, 1);
  const result = await retrieveHybridMemoryAtoms(root, 'Quasar release calendar September', { disableSemantic: true });
  assert(result.selected.some(m => m.relationReason === 'topic:rockfall relay'), 'real retrieval must include linked fact');
  const capped = await retrieveHybridMemoryAtoms(root, 'Quasar release calendar September', { disableSemantic: true, maxAtoms: 1 });
  assert.equal(capped.selected.length, 1);
  assert.match(formatMemoryAtomReferenceContext(capped), /more related facts/);
  fs.writeFileSync(path.join(root, 'MEMORY.md'), '# Memory\n## facts\n- Replacement only. [[Another Topic]]\n');
  assert.match(readRelatedMemory(root, 'rockfall relay'), /0 linked facts/);
  fs.unlinkSync(path.join(root, 'MEMORY.md'));
  assert.equal(loadMemoryTopicIndex(root).atoms.length, 0);
  fs.writeFileSync(path.join(root, 'MEMORY.md'), raw + Array.from({ length: 500 }, (_, i) => `- Miscellaneous record ${i}. [[Rockfall Relay]]`).join('\n'));
  clearHybridMemoryAtomCache();
  await retrieveHybridMemoryAtoms(root, 'Quasar release calendar September', { disableSemantic: true });
  const started = performance.now();
  for (let i = 0; i < 10; i++) await retrieveHybridMemoryAtoms(root, 'Quasar release calendar September', { disableSemantic: true });
  const average = (performance.now() - started) / 10;
  assert(average < 300, `warm retrieval ${average}ms exceeds budget`);
  assert(readRelatedMemory(root, 'rockfall relay', 500).length < 12200);
  console.log(`PASS memory topics: parser, one-hop, caps, quarantine, isolation, freshness, tagging, real hybrid retrieval; warm average ${average.toFixed(1)}ms`);
} finally { fs.rmSync(root, { recursive: true, force: true }); fs.rmSync(other, { recursive: true, force: true }); }
